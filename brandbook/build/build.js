// Infinity Story brand book generator.
// Usage: node build.js [out.pptx]
// Photos for hit items are read from ./photos/<key>.(jpg|jpeg|png); missing ones get a labeled placeholder.
const pptxgen = require("pptxgenjs");
const fs = require("fs");
const path = require("path");

const OUT = process.argv[2] || "Infinity_Story_Brandbook.pptx";
const A = (f) => path.join(__dirname, "assets", f.replace(/\.png$/, ".jpg"));
const PHOTOS = path.join(__dirname, "photos");

// ---------- palette ----------
const PEACH = "FBDCCB";
const PEACH_L = "FDEEE6";
const INK = "1E1E1E";
const MUTED = "6E655E";
const WHITE = "FFFFFF";
const DARK = "24211F";
const MOSS = "6B7A3A";
const LINE = "E9DDD5";

const HEAD = "Cambria";
const BODY = "Calibri";

const pres = new pptxgen();
pres.layout = "LAYOUT_WIDE"; // 13.333 x 7.5
pres.author = "Infinity Story";
pres.title = "Infinity Story · Бренд-бук";
const W = 13.333, H = 7.5;

let slideNo = 0;
const TOTAL = 30;

// ---------- helpers ----------
function newSlide(bg = WHITE) {
  const s = pres.addSlide();
  s.background = { color: bg };
  slideNo++;
  s._no = slideNo;
  return s;
}
function footer(s, dark = false) {
  s.addText(`${s._no} / ${TOTAL}`, {
    x: W - 1.3, y: H - 0.45, w: 0.9, h: 0.3, fontFace: BODY, fontSize: 9,
    color: dark ? "B8AEA6" : "A89E96", align: "right", isTextBox: true, margin: 0,
  });
  s.addText("INFINITY STORY", {
    x: 0.6, y: H - 0.45, w: 3, h: 0.3, fontFace: HEAD, fontSize: 9, charSpacing: 3,
    color: dark ? "B8AEA6" : "A89E96", isTextBox: true, margin: 0,
  });
}
function title(s, text, o = {}) {
  s.addText(text, {
    x: o.x ?? 0.6, y: o.y ?? 0.5, w: o.w ?? 12.1, h: o.h ?? 0.9,
    fontFace: HEAD, fontSize: o.size ?? 28, color: o.color ?? INK, bold: false,
    isTextBox: true, margin: 0, valign: "top",
  });
}
function kicker(s, text, o = {}) {
  s.addText(text.toUpperCase(), {
    x: o.x ?? 0.6, y: o.y ?? 0.25, w: o.w ?? 8, h: 0.3, fontFace: BODY, fontSize: 10,
    charSpacing: 3, color: o.color ?? MOSS, bold: true, isTextBox: true, margin: 0,
  });
}
function text(s, t, x, y, w, h, o = {}) {
  s.addText(t, {
    x, y, w, h, fontFace: o.font ?? BODY, fontSize: o.size ?? 14, color: o.color ?? INK,
    bold: o.bold ?? false, italic: o.italic ?? false, align: o.align ?? "left",
    valign: o.valign ?? "top", isTextBox: true, margin: o.margin ?? 0,
    lineSpacingMultiple: o.ls ?? 1.15, paraSpaceAfter: o.psa ?? 4, fill: o.fill,
  });
}
function bullets(s, items, x, y, w, h, o = {}) {
  const arr = items.map((it, i) => {
    if (typeof it === "string") {
      return { text: it, options: { bullet: { indent: 14 }, breakLine: i < items.length - 1 } };
    }
    return { text: it.text, options: { bullet: { indent: 14 }, bold: it.bold, breakLine: i < items.length - 1 } };
  });
  s.addText(arr, {
    x, y, w, h, fontFace: BODY, fontSize: o.size ?? 14, color: o.color ?? INK,
    valign: "top", isTextBox: true, margin: 0, paraSpaceAfter: o.psa ?? 7,
    lineSpacingMultiple: 1.12,
  });
}
function img(s, file, x, y, w, h, o = {}) {
  s.addImage({ path: file, x, y, w, h, sizing: { type: o.type ?? "cover", w, h } });
}
function rect(s, x, y, w, h, fill, o = {}) {
  s.addShape(pres.shapes.RECTANGLE, { x, y, w, h, fill: { color: fill }, line: o.line ?? { color: fill, width: 0 } });
}
function findPhoto(key) {
  for (const ext of ["jpg", "jpeg", "png", "JPG", "PNG", "webp"]) {
    const p = path.join(PHOTOS, `${key}.${ext}`);
    if (fs.existsSync(p)) return p;
  }
  return null;
}
const missingPhotos = [];
function photo(s, key, label, x, y, w, h) {
  const p = findPhoto(key);
  if (p) { img(s, p, x, y, w, h); return; }
  missingPhotos.push(`${key}  (${label})`);
  s.addShape(pres.shapes.RECTANGLE, {
    x, y, w, h, fill: { color: PEACH_L }, line: { color: "D9B9A6", width: 1, dashType: "dash" },
  });
  s.addText([
    { text: "ФОТО", options: { bold: true, fontSize: 10, charSpacing: 3, color: "B08A76", breakLine: true } },
    { text: label, options: { fontSize: 11, color: "8A6E5F", breakLine: true } },
    { text: `photos/${key}.jpg`, options: { fontSize: 8, color: "B08A76" } },
  ], { x, y, w, h, align: "center", valign: "middle", fontFace: BODY, isTextBox: true, margin: 10 });
}
function card(s, x, y, w, h, head, body, o = {}) {
  s.addShape(pres.shapes.RECTANGLE, { x, y, w, h, fill: { color: o.fill ?? PEACH_L }, line: { color: o.fill ?? PEACH_L, width: 0 } });
  if (o.num) {
    text(s, o.num, x + 0.25, y + 0.2, 0.8, 0.5, { font: HEAD, size: 26, color: o.numColor ?? MOSS });
  }
  const hh = o.headH ?? 0.5;
  const hy = y + (o.num ? 0.75 : 0.22);
  text(s, head, x + 0.25, hy, w - 0.5, hh, { font: HEAD, size: o.headSize ?? 16, color: INK, bold: false });
  text(s, body, x + 0.25, hy + hh + 0.05, w - 0.5, y + h - (hy + hh + 0.15), { size: o.bodySize ?? 12, color: MUTED, ls: 1.15 });
}
function stat(s, x, y, w, num, label, o = {}) {
  text(s, num, x, y, w, 0.9, { font: HEAD, size: o.size ?? 40, color: o.color ?? INK, align: o.align ?? "left" });
  text(s, label, x, y + 0.9, w, 0.7, { size: 12, color: o.labelColor ?? MUTED, align: o.align ?? "left" });
}
function section(num, name, sub, file) {
  const s = newSlide(DARK);
  img(s, A(file), 6.9, 0, W - 6.9, H);
  rect(s, 0, 0, 6.9, H, DARK);
  text(s, num, 0.8, 1.6, 3, 1, { font: HEAD, size: 60, color: PEACH });
  text(s, name, 0.8, 2.9, 5.6, 1.6, { font: HEAD, size: 40, color: WHITE });
  text(s, sub, 0.8, 4.6, 5.4, 1.4, { size: 15, color: "D9CFC7", ls: 1.25 });
  footer(s, true);
  return s;
}
function note(s, t) { s.addNotes(t); }

